// 失敗したときに利用者へ出す文。**文言を変えたいときは、ここだけを直す**(プロダクトごとに変えてよい)。
//
// 直すときの決まり(セキュリティ。docs/guides/error-handling.md の「利用者に出す文」):
//   1. 固定の文だけ。API の message・err.message・入力した値を埋め込まない(中身や他人の情報が漏れる)
//   2. 「どこが違ったか」を言わない。ログインの失敗で「メールアドレスが違う」「その人はいない」と書くと、
//      登録されているかどうかを確かめる手がかりになる(アカウントの列挙)。
//      パスワードを足しても「メールアドレスかパスワードが正しくありません」のように両方をまとめる
//   3. 「無い」と「見る権限が無い(他社の物)」を同じ文にする(API も同じ 404 を返している)
//   4. 中の仕組み(DB・サーバーの名前・SQL・スタック)を書かない。問い合わせには requestId を使う
// 文の中身は自由に変えてよいが、上の決まりは src/messages.test.ts が確かめる。

import type { ErrorCode } from "@app/shared";

/** API の code ごとの文。code を足したら、ここにも足す(型が止める)。 */
export const ERROR_MESSAGES: Record<ErrorCode, string> = {
  bad_request: "入力を確かめてください",
  unauthorized: "ログインが切れました。もう一度ログインしてください",
  login_failed: "ログインできませんでした",
  forbidden: "この操作の権限がありません",
  not_found: "見つかりませんでした。最新の内容を読み込み直しました",
  conflict: "ほかの変更とぶつかりました。最新の内容を読み込み直したので、もう一度試してください",
  payload_too_large: "大きすぎます。短くしてください",
  unsupported_media_type: "うまくいきませんでした。時間をおいて、もう一度試してください",
  service_unavailable:
    "いま混み合っているか、止まっています。少し待ってから、もう一度試してください",
  internal: "うまくいきませんでした。時間をおいて、もう一度試してください",
};

/** API まで届かなかったとき・それ以外の想定外。 */
export const OTHER_MESSAGES = {
  /** ブラウザから API に届かない(利用者の通信の問題かもしれない) */
  offline: "通信できませんでした。ネットの状態を確かめて、もう一度試してください",
  /** ブラウザから API へ、時間内に応答が無い */
  timeout: "時間内に応答がありませんでした。少し待ってから、もう一度試してください",
  /** 本文の無い失敗(ALB の 502 / 504 など)・想定外の値 */
  unknown: "うまくいきませんでした。時間をおいて、もう一度試してください",
} as const;

/** 問い合わせ番号の付け方。requestId はサーバーが作る ID なので、出してよい。 */
export const withRequestId = (message: string, requestId: string) =>
  `${message}(問い合わせ番号: ${requestId})`;
